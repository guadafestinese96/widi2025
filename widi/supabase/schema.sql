-- ---------------------------------------------------------------------
-- Perfumes
-- ---------------------------------------------------------------------
create table if not exists public.perfumes (
  id          bigint generated by default as identity primary key,
  marca       text not null check (char_length(marca) between 1 and 80),
  nombre      text not null check (char_length(nombre) between 1 and 120),
  genero      text not null check (genero in ('femenino', 'masculino', 'unisex')),
  precio      numeric(12,2) not null check (precio >= 0),
  stock       integer not null default 0 check (stock >= 0),
  imagen      text,
  descripcion text check (char_length(descripcion) <= 600),
  destacado   boolean not null default false,
  activo      boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- Administradores: solo los usuarios que estén en esta tabla pueden editar.
-- No tiene políticas de escritura: se cargan únicamente desde el SQL Editor.
-- ---------------------------------------------------------------------
create table if not exists public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  email   text
);

create or replace function public.es_admin()
returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

-- ---------------------------------------------------------------------
-- Pedidos (se generan al tocar "Pedir por WhatsApp")
-- ---------------------------------------------------------------------
create table if not exists public.pedidos (
  id          bigint generated by default as identity primary key,
  nombre      text check (char_length(nombre) <= 80),
  telefono    text check (char_length(telefono) <= 30),
  items       jsonb not null,               -- [{id, marca, nombre, precio, cantidad}]
  total       numeric(12,2) not null,
  estado      text not null default 'pendiente' check (estado in ('pendiente', 'confirmado', 'cancelado')),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists pedidos_fecha_idx on public.pedidos (created_at desc);

-- updated_at automático
create or replace function public.tocar_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

drop trigger if exists perfumes_updated_at on public.perfumes;
create trigger perfumes_updated_at before update on public.perfumes
  for each row execute function public.tocar_updated_at();
drop trigger if exists pedidos_updated_at on public.pedidos;
create trigger pedidos_updated_at before update on public.pedidos
  for each row execute function public.tocar_updated_at();

-- ---------------------------------------------------------------------
-- Funciones del pedido (corren en el servidor: el cliente no puede
-- inventar precios ni tocar el stock)
-- ---------------------------------------------------------------------

-- Registra un pedido con los precios REALES de la base y devuelve número y total.
-- p_items: [{"id": 3, "cantidad": 1}, ...]
create or replace function public.registrar_pedido(p_items jsonb, p_nombre text default null, p_telefono text default null)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_item     jsonb;
  v_perfume  public.perfumes%rowtype;
  v_cantidad integer;
  v_items    jsonb := '[]'::jsonb;
  v_total    numeric(12,2) := 0;
  v_id       bigint;
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'El carrito está vacío.';
  end if;
  if jsonb_array_length(p_items) > 30 then
    raise exception 'El pedido tiene demasiados productos.';
  end if;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_cantidad := (v_item->>'cantidad')::integer;
    if v_cantidad is null or v_cantidad < 1 or v_cantidad > 20 then
      raise exception 'Cantidad inválida.';
    end if;

    select * into v_perfume from public.perfumes
     where id = (v_item->>'id')::bigint and activo;
    if not found then
      raise exception 'Uno de los perfumes ya no está disponible.';
    end if;
    if v_perfume.stock < v_cantidad then
      raise exception 'No hay stock suficiente de % (quedan %).', v_perfume.nombre, v_perfume.stock;
    end if;

    v_items := v_items || jsonb_build_object(
      'id', v_perfume.id, 'marca', v_perfume.marca, 'nombre', v_perfume.nombre,
      'precio', v_perfume.precio, 'cantidad', v_cantidad);
    v_total := v_total + v_perfume.precio * v_cantidad;
  end loop;

  insert into public.pedidos (nombre, telefono, items, total)
  values (left(nullif(trim(p_nombre), ''), 80), left(nullif(trim(p_telefono), ''), 30), v_items, v_total)
  returning id into v_id;

  return jsonb_build_object('id', v_id, 'total', v_total, 'items', v_items);
end $$;

-- Confirma un pedido (cuando cobraste) y descuenta el stock. Solo admins.
create or replace function public.confirmar_pedido(p_id bigint)
returns void
language plpgsql security definer set search_path = public as $$
declare
  v_pedido public.pedidos%rowtype;
  v_item   jsonb;
begin
  if not public.es_admin() then raise exception 'No autorizado.'; end if;

  select * into v_pedido from public.pedidos where id = p_id for update;
  if not found then raise exception 'El pedido no existe.'; end if;
  if v_pedido.estado <> 'pendiente' then raise exception 'El pedido ya estaba %.', v_pedido.estado; end if;

  for v_item in select * from jsonb_array_elements(v_pedido.items) loop
    update public.perfumes
       set stock = stock - (v_item->>'cantidad')::integer
     where id = (v_item->>'id')::bigint and stock >= (v_item->>'cantidad')::integer;
    if not found then
      raise exception 'No hay stock suficiente de %.', v_item->>'nombre';
    end if;
  end loop;

  update public.pedidos set estado = 'confirmado' where id = p_id;
end $$;

-- Cancela un pedido. Si ya estaba confirmado, devuelve el stock. Solo admins.
create or replace function public.cancelar_pedido(p_id bigint)
returns void
language plpgsql security definer set search_path = public as $$
declare
  v_pedido public.pedidos%rowtype;
  v_item   jsonb;
begin
  if not public.es_admin() then raise exception 'No autorizado.'; end if;

  select * into v_pedido from public.pedidos where id = p_id for update;
  if not found then raise exception 'El pedido no existe.'; end if;
  if v_pedido.estado = 'cancelado' then return; end if;

  if v_pedido.estado = 'confirmado' then
    for v_item in select * from jsonb_array_elements(v_pedido.items) loop
      update public.perfumes set stock = stock + (v_item->>'cantidad')::integer
       where id = (v_item->>'id')::bigint;
    end loop;
  end if;

  update public.pedidos set estado = 'cancelado' where id = p_id;
end $$;

revoke all on function public.registrar_pedido(jsonb, text, text) from public;
revoke all on function public.confirmar_pedido(bigint) from public;
revoke all on function public.cancelar_pedido(bigint) from public;
grant execute on function public.registrar_pedido(jsonb, text, text) to anon, authenticated;
grant execute on function public.confirmar_pedido(bigint) to authenticated;
grant execute on function public.cancelar_pedido(bigint) to authenticated;
grant execute on function public.es_admin() to anon, authenticated;

-- ---------------------------------------------------------------------
-- Seguridad por filas (RLS)
-- ---------------------------------------------------------------------
alter table public.perfumes enable row level security;
alter table public.admins   enable row level security;
alter table public.pedidos  enable row level security;

-- Cualquiera ve los perfumes activos; el admin ve todos.
drop policy if exists "perfumes_lectura" on public.perfumes;
create policy "perfumes_lectura" on public.perfumes
  for select to anon, authenticated using (activo or public.es_admin());

-- Solo el admin crea, edita o borra perfumes.
drop policy if exists "perfumes_admin" on public.perfumes;
create policy "perfumes_admin" on public.perfumes
  for all to authenticated using (public.es_admin()) with check (public.es_admin());

-- Cada admin puede verse a sí mismo (para que la app sepa que es admin).
drop policy if exists "admins_propio" on public.admins;
create policy "admins_propio" on public.admins
  for select to authenticated using (user_id = auth.uid());

-- Los pedidos solo los ve y modifica el admin. Nadie inserta directo:
-- se crean únicamente con registrar_pedido().
drop policy if exists "pedidos_admin" on public.pedidos;
create policy "pedidos_admin" on public.pedidos
  for select to authenticated using (public.es_admin());
drop policy if exists "pedidos_admin_borrar" on public.pedidos;
create policy "pedidos_admin_borrar" on public.pedidos
  for delete to authenticated using (public.es_admin());

